export function childrenOf(id: string | null): ComponentInfo[] {
  return list.filter((c) => c.parent === id);
}

export function ancestorsOf(id: string): string[] {
  const out: string[] = [];
  let cur = COMPONENTS[id]?.parent ?? null;
  while (cur) {
    out.push(cur);
    cur = COMPONENTS[cur]?.parent ?? null;
  }
  return out;
}

