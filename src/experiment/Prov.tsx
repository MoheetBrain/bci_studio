// Provenance labels. Every major representation in the experiment carries exactly one of these five.
import './experiment.css';

export type ProvKind = 'measured' | 'atlas' | 'simulated' | 'inferred' | 'illustrative';
export const PROV: Record<ProvKind, { label: string; long: string }> = {
  measured: { label: 'MEASURED DATA', long: 'Recorded or imaged data (the atlas MRI, or the RTL simulation trace built on recorded ECoG). Not produced by a model in this app.' },
  atlas: { label: 'ATLAS-DERIVED', long: 'Computed directly from the atlas files: labels, mesh geometry and coordinates of one volunteer.' },
  simulated: { label: 'SIMULATED', long: 'Numbers generated by a stated model from stated parameters and a fixed seed. Not a recording.' },
  inferred: { label: 'MODEL-INFERRED', long: 'An estimate computed from other (here: simulated) signals by a fitted or stated model — a decoder output, a noise estimate, a cost estimate.' },
  illustrative: { label: 'ILLUSTRATIVE', long: 'A drawing or simplified shape chosen to explain. Not data and not to scale unless a scale is given.' },
};

export function Prov({ kind, title, note }: { kind: ProvKind; title?: string; note?: string }) {
  return (
    <span className={`prov prov-${kind}`} title={title ?? PROV[kind].long} data-prov={kind}>
      <i aria-hidden="true" />{PROV[kind].label}{note ? <em> · {note}</em> : null}
    </span>
  );
}
